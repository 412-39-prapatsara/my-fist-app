import time


def play_game():
    # ข้อมูลคำถาม คำตอบ และคำใบ้
    questions = [
        {
            "hint": "🐷🌿🔥 หมู + ใบเขียว + พริก + กระทะไฟแรง = ?",
            "answer": "ผัดกะเพรา",
        },
        {
            "hint": "🍜🥜🦐🍋 เส้น + ถั่ว + กุ้ง + มะนาว = ?",
            "answer": "ผัดไทย",
        },
        {
            "hint": "🦐🌶️🍋🔥 กุ้ง + พริก + มะนาว + น้ำซุปร้อนๆ = ?",
            "answer": "ต้มยำกุ้ง",
        },
        {
            "hint": "🥒🌶️🥜🦀 ผักกรอบๆ + พริก + ถั่ว + ของทะเล = ?",
            "answer": "ส้มตำ",
        },
        {
            "hint": "🍗🥥🌿🌶️ ไก่ + กะทิ + เครื่องแกง + ใบหอมๆ = ?",
            "answer": "แกงเขียวหวาน",
        },
        {
            "hint": "🍖🥔🥥🧅 เนื้อนุ่ม + มันฝรั่ง + กะทิ + หอมใหญ่ + เครื่องเทศ = ?",
            "answers": ["มัสมั่นไก่", "มัสมั่นเนื้อ", "มัสมั่น"],
            "display_ans": "มัสมั่นไก่/เนื้อ",
        },
        {
            "hint": "🍗🧂🔥 ไก่ + น้ำปลา + ทอดจนกรอบ = ?",
            "answer": "ไก่ทอด",
        },
        {
            "hint": "🍚🐔🥒🥣 ข้าวมันๆ + ไก่นุ่ม + แตงกวา + น้ำจิ้ม = ?",
            "answer": "ข้าวมันไก่",
        },
        {
            "hint": "🐷🔥🥩🌶️ หมูส่วนมันๆ + ย่างไฟ + น้ำจิ้มแจ่ว = ?",
            "answer": "คอหมูย่าง",
        },
        {
            "hint": "🦐🧄🌶️🧂 กุ้ง + กระเทียมเยอะๆ + พริก + รสเค็มๆ = ?",
            "answer": "กุ้งผัดพริกเกลือ",
        },
        {
            "hint": "🥚🐷🧂🍳 ไข่ฟูๆ + หมูสับ + ทอดในน้ำมัน = ?",
            "answer": "ไข่เจียวหมูสับ",
        },
        {
            "hint": "🐷🥚🍚🥬 หมูตุ๋นนุ่มๆ + ไข่ + ข้าวสวย + ผักดอง = ?",
            "answer": "ข้าวขาหมู",
        },
    ]

    score = 0
    total_questions = len(questions)

    print("==========================================")
    print("      🎉 ยินดีต้อนรับสู่เกมทายเมนูอาหารไทย! 🎉")
    print("==========================================")
    print("คำชี้แจง: ทายชื่อเมนูอาหารจากคำใบ้และ Emoji ต่อไปนี้\n")

    for i, q in enumerate(questions, 1):
        print(f"ข้อที่ {i}/{total_questions}")
        print(f"คำใบ้: {q['hint']}")

        user_answer = input("คำตอบของคุณ: ").strip()

        # ตรวจคำตอบ (รองรับกรณีมัสมั่นที่มีหลายคำตอบ)
        is_correct = False
        if "answers" in q:
            if user_answer in q["answers"]:
                is_correct = True
        else:
            if user_answer == q["answer"]:
                is_correct = True

        if is_correct:
            print("✅ ถูกต้องครับ/ค่ะ!\n")
            score += 1
        else:
            correct_display = q.get("display_ans", q.get("answer"))
            print(f"❌ ผิดครับ/ค่ะ! คำตอบที่ถูกต้องคือ: {correct_display}\n")

        time.sleep(0.5)

    # สรุปผลคะแนน
    print("==========================================")
    print(f"🎯 จบเกมแล้ว! คุณได้คะแนนทั้งหมด: {score}/{total_questions} คะแนน")

    # ประเมินเกณฑ์
    if score == 12:
        rating = "🏆 ระดับยอดเยี่ยม"
    elif 6 <= score <= 11:
        rating = "👍 ระดับดี"
    elif 1 <= score <= 5:
        rating = "✌️ พยายามอีกนิด"
    else:
        rating = "💀 แพ้"

    print(f"📊 ผลการประเมิน: {rating}")
    print("==========================================")

if __name__ == "__main__":
       play_game()
